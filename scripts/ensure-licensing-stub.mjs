// predev/prebuild 前置腳本。src/licensing/verify.local.ts 是 gitignored(見
// .gitignore),永遠不在這個 repo 的 git 歷史裡 —— 但 src/licensing/index.ts
// 對它做的是**靜態** import,Cloudflare Workers 部署又沒有 runtime 檔案系統,
// 所以 webpack/Turbopack 必須在 build 當下就能解析到這個檔案,否則整個 build
// 失敗(dynamic import + try/catch 在這裡沒用,見 index.ts 的說明)。
//
// 這支腳本補的就是這個缺口:build 開始前,若 verify.local.ts 不存在,就自動
// 產生一份指向 community 預設實作的 stub。open-source clone 永遠會走到這條
// 路徑(檔案從未存在過)、產出零商業邏輯的 build。若 verify.local.ts 已經
// 存在(commercial 部署,人工放上去的真實檔案),這支腳本完全不動它。
import { existsSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const target = join(__dirname, "..", "src", "licensing", "verify.local.ts");

const STUB = `// AUTO-GENERATED by scripts/ensure-licensing-stub.mjs — this file did not
// exist on disk at build time, so a community-mode stub was created here.
// This is expected and correct for an open-source checkout. Do not hand-edit:
// it will be silently left alone (not regenerated) once any file exists at
// this path, but a hand-edited stub with no real content serves no purpose —
// see src/licensing/index.ts for why this file must always exist for the
// build to succeed on Cloudflare Workers.
import { communityVerify } from "./verify";
import type { LicenseVerifier } from "./types";

export const verifier: LicenseVerifier = communityVerify;
`;

if (!existsSync(target)) {
  writeFileSync(target, STUB, "utf8");
  console.log("[licensing] verify.local.ts absent — generated community-mode stub.");
}
